import { Language } from './translations';

interface Text {
  title: string;
  content: string;
  questions: Array<{
    question: string;
    options: string[];
    correctAnswer: number;
  }>;
}

export function getRandomText(language: Language, difficulty: 'easy' | 'medium' | 'hard', wpm: number = 60): Text {
  const textsForDifficulty = texts[language][difficulty];
  const randomIndex = Math.floor(Math.random() * textsForDifficulty.length);
  const baseText = textsForDifficulty[randomIndex];
  
  // Calculate how many words we need for at least 30 seconds of reading
  const wordsNeeded = (wpm * 30) / 60; // 30 seconds worth of words
  const currentWords = baseText.content.split(' ').length;
  
  // If text is already long enough, return as is
  if (currentWords >= wordsNeeded) {
    return baseText;
  }
  
  // Otherwise, expand the text by repeating it
  const repetitions = Math.ceil(wordsNeeded / currentWords);
  let expandedContent = baseText.content;
  
  for (let i = 1; i < repetitions; i++) {
    expandedContent += ' ' + baseText.content;
  }
  
  return {
    ...baseText,
    content: expandedContent
  };
}

